// 职责：模块把自己的世界状态暴露给回放系统的契约——只有「写成字节」和「从字节读回来」这一对操作。
//   实现它的是玩法模块里那些「变了就会影响后续逻辑」的数据持有者（实体表、计时器、随机流状态……）。
// 为什么不复用、不扩展（加能力的顺序：复用 → 扩展 → 新建）：
//   1. 复用不行：工程内唯一的「把自己存下来」契约是 Core/Save/ISaveData，但它是 JSON 存档分区，
//      面向人读与跨版本迁移，靠字段名匹配、允许字段缺失、要求老档一路能读；
//      这里要的是定长二进制、按顺序定位、字段一变老录像就作废（理由见 IStateWriter 文件头）。
//      让同一个类同时当存档分区和回放状态，等于把两套相反的兼容策略绑在一组字段上，
//      以后加一个字段要同时满足「老档还能读」和「老录像必须拒」，必然有一边写错。
//   2. 扩展不行：不能把这两个方法加进 Simulation/ISimulationStep。那个接口的职责是「推进一个 tick」，
//      而且方向是反的——Core/Simulation 是确定性内核，不认识回放系统（依赖只许 Replay → Simulation）。
//      往 ISimulationStep 上挂序列化，会让内核反过来依赖回放层，也会逼着每个步骤都实现序列化，
//      可有的步骤根本没有状态（纯函数），有的状态又不属于任何步骤（比如跨步骤共享的实体表）。

namespace Game.Core.Replay
{
    /// <summary>
    /// 一份可进快照、可进状态哈希的世界状态。模块实现它来暴露自己「变了就会影响后续逻辑」的那些数据。
    /// <para>
    /// **两个方法必须逐行镜像**：写了几个字段就读几个字段，顺序、类型、条件分支全都要一一对应。
    /// 定长二进制里没有字段名也没有长度前缀，读写错开一个字段，后面全部错位，而且通常不会抛异常，
    /// 只会读出一堆看起来合理的垃圾值。
    /// </para>
    /// <para>
    /// **该写什么**：所有会影响后续逻辑的数据，一个不能少。少写一个字段，这个字段的漂移就永远查不出来——
    /// 哈希一直相等，重放「看起来没漂移」，而你还在信任这个机制（这也正是哈希必须由框架统一算、
    /// 模块不许自己实现的原因，见 <see cref="StateHasher"/>）。
    /// </para>
    /// <para>
    /// **该不写什么**：纯表现数据（插值位置、特效、音量、UI 动画进度）不写。它们不参与逻辑，
    /// 写进去只会让哈希跟着表现抖，把真正的逻辑漂移淹掉。判据不是「这个值变不变」，
    /// 而是「这个值变了，下一 tick 的逻辑会不会不一样」。
    /// </para>
    /// <para>
    /// **不要写条件字段**：别写成「Debug 下多写一个字段」或「这个开关开着才写」。编辑器里录的、
    /// 真机上放的，字节布局必须完全一样，否则跨端重放第一帧就崩。
    /// </para>
    /// <para>分配约定：两个方法都在周期性路径上（哈希每秒一次、快照每十秒一次），实现里不要 new、不要拼字符串。</para>
    /// </summary>
    public interface IReplayState
    {
        /// <summary>
        /// 把自己的状态写进 <paramref name="writer"/>。写入顺序即字节布局，改顺序 = 改格式。
        /// </summary>
        void Serialize(IStateWriter writer);

        /// <summary>
        /// 从 <paramref name="reader"/> 把状态读回来，**顺序必须和 <see cref="Serialize"/> 完全一致**。
        /// 读完之后对象应该和当初写出去时处于完全相同的逻辑状态——「几乎相同」在重放里等于不同。
        /// </summary>
        void Deserialize(IStateReader reader);
    }
}
