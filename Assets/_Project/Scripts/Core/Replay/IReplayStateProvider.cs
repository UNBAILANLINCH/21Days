// 职责：世界状态的注册表契约——模块把自己的 IReplayState 注册进来，框架按注册顺序统一收集、
//   一次性序列化成一段连续字节（状态哈希与完整快照都从这一段字节来）。
// 为什么不复用、不扩展（加能力的顺序：复用 → 扩展 → 新建）：
//   1. 复用不行：工程内没有任何「按固定顺序收集一组对象再统一序列化」的设施。
//      Core/Save/ISaveService 的 Get<T>() 是按类型取分区、顺序无关的字典语义，
//      而这里顺序就是字节布局本身（见下面的顺序契约），把它建在字典语义上等于把布局交给运行时决定。
//      VContainer 的容器解析同理：解析顺序不是稳定契约，不能拿来当字节布局。
//   2. 扩展不行：不能挂到 Simulation/SimulationRunner.AddStep 那条注册链上。它注册的是「推进逻辑」，
//      本接口注册的是「状态数据」，两者既不是同一批对象（有的步骤无状态，有的状态不属于任何步骤），
//      顺序要求也不同（步骤顺序按依赖排，状态顺序一旦定下就不许动）。更硬的一条：
//      Core/Simulation 是确定性内核，不认识回放系统，依赖方向只许 Replay → Simulation。

namespace Game.Core.Replay
{
    /// <summary>
    /// 世界状态注册表。开局接线时各模块把自己的 <see cref="IReplayState"/> 注册进来，
    /// 之后由回放系统统一调 <see cref="SerializeAll"/> / <see cref="DeserializeAll"/>。
    /// <para>
    /// **注册顺序即序列化顺序，也就是字节布局本身。** 收集时严格按注册先后遍历，
    /// 第 1 个注册的状态写在最前面。所以：
    /// </para>
    /// <para>
    /// ① 顺序变了，同一份字节就会被按错误的顺序解读——老录像不是「读出来有点偏」，而是从第一个字段起
    /// 全部对不上，还多半不抛异常（类型宽度碰巧对得上就读成垃圾值）。
    /// **注册顺序的任何变更（含增删注册项）都必须同步升回放格式版本号**，靠版本号把老录像硬拒掉，
    /// 而不是让它半读半错地跑起来。
    /// </para>
    /// <para>
    /// ② 注册必须发生在确定的接线点上，顺序由代码写死。绝对不要让注册顺序取决于
    /// 场景加载先后、字典/反射的遍历顺序、或者「谁先 Awake」——那样同一份代码在两台机器上
    /// 就可能排出两种布局，而这种问题只会在别人的机器上偶发。
    /// </para>
    /// <para>
    /// **没有注销**：注册表是开局接线时定死的，中途移除会让同一次运行前后两段快照的布局不一致，
    /// 跳转回一个旧快照时就会按错误布局恢复。要换一批状态，只能整局重来。
    /// </para>
    /// </summary>
    public interface IReplayStateProvider
    {
        /// <summary>已注册的状态数量，供接线自检与调试台查看。</summary>
        int Count { get; }

        /// <summary>
        /// 注册一份世界状态。**调用顺序即序列化顺序**，约束见接口文档。
        /// 同一个实例不要注册两次（会被写两遍，哈希与快照都跟着翻倍）。
        /// </summary>
        /// <param name="state">要纳入快照与哈希的状态对象，不可为空。</param>
        void Register(IReplayState state);

        /// <summary>
        /// 按注册顺序把所有状态写进 <paramref name="writer"/>，拼成一段连续字节。
        /// 状态哈希与完整快照都用这一段字节，**不存在第二条取字节的路径**——
        /// 因此不可能出现「进了快照但没进哈希」的字段。
        /// </summary>
        void SerializeAll(IStateWriter writer);

        /// <summary>
        /// 按注册顺序把所有状态从 <paramref name="reader"/> 读回来，顺序与 <see cref="SerializeAll"/> 严格一致。
        /// 读完之后整个世界应当与当初写出去的那一刻完全相同。
        /// </summary>
        void DeserializeAll(IStateReader reader);
    }
}
